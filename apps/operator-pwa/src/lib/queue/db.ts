import type { QueueItem } from './types';

/**
 * The IndexedDB layer: one database, a `queue` object store (autoincrement `seq` = capture order) and a `kv` store for
 * small cached documents (my tasks, profile, site). No credentials are ever written here (BLUEPRINT section 18): the
 * access token lives in memory only.
 */
export const DB_NAME = 'vo-operator';
const DB_VERSION = 1;

export interface QueueStore {
  add(item: Omit<QueueItem, 'seq'>): Promise<QueueItem>;
  get(seq: number): Promise<QueueItem | undefined>;
  put(item: QueueItem): Promise<void>;
  list(): Promise<QueueItem[]>;
  remove(seq: number): Promise<void>;
  kvGet<T>(key: string): Promise<T | undefined>;
  kvSet(key: string, value: unknown): Promise<void>;
  kvRemove(key: string): Promise<void>;
  kvKeys(): Promise<string[]>;
  /** Called after every change to the queue (in this tab); returns an unsubscribe function. */
  subscribe(listener: () => void): () => void;
  close(): void;
}

function request<T>(req: IDBRequest<T>): Promise<T> {
  return new Promise((resolve, reject) => {
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error ?? new Error('IndexedDB request failed'));
  });
}

function done(tx: IDBTransaction): Promise<void> {
  return new Promise((resolve, reject) => {
    tx.oncomplete = () => resolve();
    tx.onerror = () => reject(tx.error ?? new Error('IndexedDB transaction failed'));
    tx.onabort = () => reject(tx.error ?? new Error('IndexedDB transaction aborted'));
  });
}

export function openQueueStore(
  factory: IDBFactory = globalThis.indexedDB,
  name: string = DB_NAME,
): Promise<QueueStore> {
  return new Promise((resolve, reject) => {
    const open = factory.open(name, DB_VERSION);
    open.onupgradeneeded = () => {
      const db = open.result;
      if (!db.objectStoreNames.contains('queue')) {
        db.createObjectStore('queue', { keyPath: 'seq', autoIncrement: true });
      }
      if (!db.objectStoreNames.contains('kv')) db.createObjectStore('kv');
    };
    open.onerror = () => reject(open.error ?? new Error('IndexedDB open failed'));
    open.onsuccess = () => {
      const db = open.result;
      const listeners = new Set<() => void>();
      const notify = () => listeners.forEach((l) => l());

      const store: QueueStore = {
        async add(item) {
          const tx = db.transaction('queue', 'readwrite');
          const objects = tx.objectStore('queue');
          // `seq` is generated by the store (autoIncrement, inline key path): the key is written into the value.
          const key = await request(objects.add(item));
          const stored = { ...item, seq: Number(key) } as QueueItem;
          await done(tx);
          notify();
          return stored;
        },
        async get(seq) {
          const tx = db.transaction('queue', 'readonly');
          return (await request(tx.objectStore('queue').get(seq))) as QueueItem | undefined;
        },
        async put(item) {
          const tx = db.transaction('queue', 'readwrite');
          tx.objectStore('queue').put(item);
          await done(tx);
          notify();
        },
        async list() {
          const tx = db.transaction('queue', 'readonly');
          const all = (await request(tx.objectStore('queue').getAll())) as QueueItem[];
          return all.sort((a, b) => a.seq - b.seq);
        },
        async remove(seq) {
          const tx = db.transaction('queue', 'readwrite');
          tx.objectStore('queue').delete(seq);
          await done(tx);
          notify();
        },
        async kvGet<T>(key: string) {
          const tx = db.transaction('kv', 'readonly');
          return (await request(tx.objectStore('kv').get(key))) as T | undefined;
        },
        async kvSet(key, value) {
          const tx = db.transaction('kv', 'readwrite');
          tx.objectStore('kv').put(value, key);
          await done(tx);
        },
        async kvRemove(key) {
          const tx = db.transaction('kv', 'readwrite');
          tx.objectStore('kv').delete(key);
          await done(tx);
        },
        async kvKeys() {
          const tx = db.transaction('kv', 'readonly');
          return (await request(tx.objectStore('kv').getAllKeys())).map(String);
        },
        subscribe(listener) {
          listeners.add(listener);
          return () => listeners.delete(listener);
        },
        close() {
          db.close();
        },
      };
      resolve(store);
    };
  });
}
